import { APP_NAME, DEFAULT_KEY_PREFIX } from "../shared/constants.ts";
import type { PopupKind } from "../shared/protocol.ts";

/** Quotes a value for a tmux config file or command string. */
export function tmuxQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** The shell command that runs the dwa CLI for a project, as tmux needs it for popups and keys. */
export function selfCommand(selfArgv: string[], projectRoot: string): string {
  return `DWA_PROJECT=${tmuxQuote(projectRoot)} ${selfArgv.map(tmuxQuote).join(" ")}`;
}

const POPUPS: Record<PopupKind, { title: string; command: string; width: number; height: number }> =
  {
    // As large as the designer's, which can be opened from this one: a popup keeps its size.
    workflows: { title: "Workflows", command: "wizard workflows", width: 90, height: 90 },
    agent: { title: "New agent", command: "wizard agent", width: 70, height: 80 },
    tools: { title: "Agent tools", command: "wizard tools", width: 70, height: 90 },
    roles: { title: "Role settings", command: "wizard roles", width: 70, height: 90 },
    design: { title: "Workflow designer", command: "wizard design", width: 90, height: 90 },
    questions: { title: "Questions", command: "answer", width: 80, height: 60 },
    palette: { title: APP_NAME, command: "palette", width: 60, height: 70 },
  };

/** tmux arguments that open one of dwa's popups over the workspace. */
export function popupArgs(self: string, kind: PopupKind, subject?: string): string[] {
  const { title, width, height } = POPUPS[kind];
  // What the popup is about (a session for the tools dialog) goes to its command as a word.
  const command = subject ? `${POPUPS[kind].command} ${tmuxQuote(subject)}` : POPUPS[kind].command;
  return [
    "display-popup",
    "-E",
    "-w",
    `${width}%`,
    "-h",
    `${height}%`,
    "-T",
    ` ${title} `,
    `${self} ${command}`,
  ];
}

export interface ConfOptions {
  /** Key pressed before a dwa shortcut, in tmux notation. */
  prefix?: string;
  /** Command that runs the dwa CLI for this project, e.g. [bun, /path/to/cli/index.ts]. */
  selfArgv: string[];
  projectRoot: string;
}

/**
 * The private tmux server's config. Terminal settings are the ones verified with Claude Code in
 * docs/spikes.md (S1). Shortcuts are reached through a prefix key (Ctrl+Q by default), which
 * works on every keyboard layout. The same actions are also bound to Alt for terminals that send
 * Option as Meta. tmux's own default bindings are removed so nothing unexpected is reachable.
 */
export function buildTmuxConf(options: ConfOptions): string {
  const dwa = selfCommand(options.selfArgv, options.projectRoot);
  const popup = (kind: PopupKind) =>
    popupArgs(dwa, kind)
      .map((arg, index) => (index === 0 || /^-[A-Za-z]$|^\d+%$/.test(arg) ? arg : tmuxQuote(arg)))
      .join(" ");
  const run = (command: string) => `run-shell -b ${tmuxQuote(`${dwa} ${command}`)}`;
  const prefix = options.prefix ?? DEFAULT_KEY_PREFIX;
  const actions: [key: string, command: string][] = [
    ...Array.from({ length: 9 }, (_, i): [string, string] => [
      `${i + 1}`,
      run(`key open ${i + 1}`),
    ]),
    ["x", run("key close")],
    ["s", run("key shell")],
    ["w", popup("workflows")],
    ["a", popup("agent")],
    ["t", popup("tools")],
    ["r", popup("roles")],
    ["g", popup("design")],
    ["0", run("key focus")],
    ["z", "resize-pane -Z"],
    ["p", popup("palette")],
    ["q", popup("questions")],
  ];
  const lines = [
    "# Generated by dwa. Changes are overwritten on the next `dwa up`.",
    'set -g default-terminal "tmux-256color"',
    "set -as terminal-features 'xterm*:extkeys'",
    "set -g allow-passthrough on",
    "set -g focus-events on",
    "set -g extended-keys always",
    "set -g extended-keys-format csi-u",
    "set -g mouse on",
    "set -g escape-time 0",
    "set -g history-limit 20000",
    "set -g status off",
    "set -g remain-on-exit on",
    "set -g pane-border-status top",
    "set -g pane-border-format ' #{pane_title} '",
    "",
    "# Shortcuts: <prefix> then 1..9 opens that agent under main, x closes it, 0 focuses main,",
    "# s shows or hides the shell, w opens the workflows wizard, a the new-agent wizard,",
    "# t the tools of a session, r the role settings, g the workflow designer,",
    "# p opens the command menu, q answers open questions, z zooms the focused pane, d detaches. Pressing the prefix twice sends it to the program.",
    "unbind -a -T prefix",
    "unbind -a -T root",
    `set -g prefix ${prefix}`,
    "set -g prefix2 None",
    `bind ${prefix} send-prefix`,
    "bind d detach-client",
    ...actions.map(([key, command]) => `bind ${key} ${command}`),
    "",
    "# The same actions on Alt, for terminals that send Option as Meta.",
    ...actions.map(([key, command]) => `bind -n M-${key} ${command}`),
    "",
    "# Mouse: click focuses a pane, drag on a border resizes, wheel scrolls.",
    "bind -n MouseDown1Pane select-pane -t = \\; send-keys -M",
    "bind -n MouseDrag1Border resize-pane -M",
    "bind -n WheelUpPane if-shell -F -t = '#{||:#{mouse_any_flag},#{alternate_on}}' 'send-keys -M' 'copy-mode -e -t ='",
    "",
  ];
  return lines.join("\n");
}
