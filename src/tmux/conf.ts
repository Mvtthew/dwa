import { DEFAULT_KEY_PREFIX } from "../shared/constants.ts";

/** Quotes a value for a tmux config file or command string. */
export function tmuxQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export interface ConfOptions {
  /** Key pressed before a dwa shortcut, in tmux notation. */
  prefix?: string;
  /** Command that runs the dwa CLI for this project, e.g. [bun, /path/to/cli/index.ts]. */
  selfArgv: string[];
  projectRoot: string;
}

/**
 * The private tmux server's config. Terminal settings are the ones verified with Claude Code in
 * docs/spikes.md (S1). Shortcuts are reached through a prefix key (Ctrl+Q by default), which
 * works on every keyboard layout. The same actions are also bound to Alt for terminals that send
 * Option as Meta. tmux's own default bindings are removed so nothing unexpected is reachable.
 */
export function buildTmuxConf(options: ConfOptions): string {
  const dwa = `DWA_PROJECT=${tmuxQuote(options.projectRoot)} ${options.selfArgv.map(tmuxQuote).join(" ")}`;
  const run = (command: string) => `run-shell -b ${tmuxQuote(`${dwa} ${command}`)}`;
  const prefix = options.prefix ?? DEFAULT_KEY_PREFIX;
  const actions: [key: string, command: string][] = [
    ...Array.from({ length: 9 }, (_, i): [string, string] => [
      `${i + 1}`,
      run(`key open ${i + 1}`),
    ]),
    ["x", run("key close")],
    ["0", run("key focus")],
    ["z", "resize-pane -Z"],
  ];
  const lines = [
    "# Generated by dwa. Changes are overwritten on the next `dwa up`.",
    'set -g default-terminal "tmux-256color"',
    "set -as terminal-features 'xterm*:extkeys'",
    "set -g allow-passthrough on",
    "set -g focus-events on",
    "set -g extended-keys always",
    "set -g extended-keys-format csi-u",
    "set -g mouse on",
    "set -g escape-time 0",
    "set -g history-limit 20000",
    "set -g status off",
    "set -g remain-on-exit on",
    "set -g pane-border-status top",
    "set -g pane-border-format ' #{pane_title} '",
    "",
    "# Shortcuts: <prefix> then 1..9 opens that agent under main, x closes it, 0 focuses main,",
    "# z zooms the focused pane, d detaches. Pressing the prefix twice sends it to the program.",
    "unbind -a -T prefix",
    "unbind -a -T root",
    `set -g prefix ${prefix}`,
    "set -g prefix2 None",
    `bind ${prefix} send-prefix`,
    "bind d detach-client",
    ...actions.map(([key, command]) => `bind ${key} ${command}`),
    "",
    "# The same actions on Alt, for terminals that send Option as Meta.",
    ...actions.map(([key, command]) => `bind -n M-${key} ${command}`),
    "",
    "# Mouse: click focuses a pane, drag on a border resizes, wheel scrolls.",
    "bind -n MouseDown1Pane select-pane -t = \\; send-keys -M",
    "bind -n MouseDrag1Border resize-pane -M",
    "bind -n WheelUpPane if-shell -F -t = '#{||:#{mouse_any_flag},#{alternate_on}}' 'send-keys -M' 'copy-mode -e -t ='",
    "",
  ];
  return lines.join("\n");
}
