/** Quotes a value for a tmux config file or command string. */
export function tmuxQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export interface ConfOptions {
  /** Command that runs the dwa CLI for this project, e.g. [bun, /path/to/cli/index.ts]. */
  selfArgv: string[];
  projectRoot: string;
}

/**
 * The private tmux server's config. Terminal settings are the ones verified with Claude Code in
 * docs/spikes.md (S1). Key bindings use Alt in the root table so they work without a prefix and
 * take nothing from Claude Code.
 */
export function buildTmuxConf(options: ConfOptions): string {
  const dwa = `DWA_PROJECT=${tmuxQuote(options.projectRoot)} ${options.selfArgv.map(tmuxQuote).join(" ")}`;
  const run = (command: string) => `run-shell -b ${tmuxQuote(`${dwa} ${command}`)}`;
  const lines = [
    "# Generated by dwa. Changes are overwritten on the next `dwa up`.",
    'set -g default-terminal "tmux-256color"',
    "set -as terminal-features 'xterm*:extkeys'",
    "set -g allow-passthrough on",
    "set -g focus-events on",
    "set -g extended-keys always",
    "set -g extended-keys-format csi-u",
    "set -g mouse on",
    "set -g escape-time 0",
    "set -g history-limit 20000",
    "set -g status off",
    "set -g remain-on-exit on",
    "set -g pane-border-status top",
    "set -g pane-border-format ' #{pane_title} '",
    "",
    "# Alt+1..9 open the agent at that position under main, Alt+x closes it.",
    ...Array.from({ length: 9 }, (_, i) => `bind -n M-${i + 1} ${run(`agent open ${i + 1}`)}`),
    `bind -n M-x ${run("agent close")}`,
    `bind -n M-0 ${run("focus main")}`,
    "bind -n M-z resize-pane -Z",
    "",
  ];
  return lines.join("\n");
}
